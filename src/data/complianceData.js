// Calculation Engine for Compliance Metrics
export function calculateComplianceMetrics(cohort = COMPLIANCE_COHORT_DATA, mous = CORPORATE_MOUS_DATA) {
  const totalGraduatingCohort = cohort.length;
  const placedStudents = cohort.filter((s) => s.outcomeCategory === 'GO-P');
  const higherStudiesStudents = cohort.filter((s) => s.outcomeCategory === 'GO-HS');
  const entrepreneurStudents = cohort.filter((s) => s.outcomeCategory === 'GO-E');

  const totalPlacedCount = placedStudents.length;
  const totalHigherStudiesCount = higherStudiesStudents.length;
  const totalEntrepreneurCount = entrepreneurStudents.length;

  // Placement % (Direct Placed / Total Cohort)
  const directPlacementPercent = totalGraduatingCohort > 0 
    ? Number(((totalPlacedCount / totalGraduatingCohort) * 100).toFixed(1))
    : 0;

  // Total Progression % (Placed + Higher Studies + Entrepreneurship / Total Cohort)
  const totalProgressionCount = totalPlacedCount + totalHigherStudiesCount + totalEntrepreneurCount;
  const totalProgressionPercent = totalGraduatingCohort > 0
    ? Number(((totalProgressionCount / totalGraduatingCohort) * 100).toFixed(1))
    : 0;

  // Calculate Median Salary from Placed Graduates
  const sortedSalaries = placedStudents
    .map((s) => s.packageNumeric)
    .filter((v) => typeof v === 'number' && v > 0)
    .sort((a, b) => a - b);

  let medianSalaryNumeric = 850000;
  if (sortedSalaries.length > 0) {
    const mid = Math.floor(sortedSalaries.length / 2);
    medianSalaryNumeric =
      sortedSalaries.length % 2 !== 0
        ? sortedSalaries[mid]
        : Math.round((sortedSalaries[mid - 1] + sortedSalaries[mid]) / 2);
  }

  const medianSalaryLpa = (medianSalaryNumeric / 100000).toFixed(2);

  // Average Package
  const totalSalarySum = sortedSalaries.reduce((acc, curr) => acc + curr, 0);
  const averageSalaryNumeric = sortedSalaries.length > 0 ? Math.round(totalSalarySum / sortedSalaries.length) : 0;
  const averageSalaryLpa = (averageSalaryNumeric / 100000).toFixed(2);

  // Highest Package
  const highestSalaryNumeric = sortedSalaries.length > 0 ? sortedSalaries[sortedSalaries.length - 1] : 0;
  const highestSalaryLpa = (highestSalaryNumeric / 100000).toFixed(2);

  // Corporate MoU count
  const corporateMouCount = mous.length;

  return {
    totalGraduatingCohort,
    totalPlacedCount,
    totalHigherStudiesCount,
    totalEntrepreneurCount,
    totalProgressionCount,
    directPlacementPercent,
    totalProgressionPercent,
    medianSalaryNumeric,
    medianSalaryLpa,
    averageSalaryNumeric,
    averageSalaryLpa,
    highestSalaryNumeric,
    highestSalaryLpa,
    corporateMouCount
  };
}

